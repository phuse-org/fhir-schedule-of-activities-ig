# ---------------------------------------------------------------------------
# Slugify helper
# ---------------------------------------------------------------------------
# Characters to convert to hyphens (spaces, slashes, commas, parentheses)
_SLUG_TO_HYPHEN = re.compile(r"[\s/,()+]+")
# Characters to strip entirely (anything not alphanumeric or hyphen)
_SLUG_STRIP = re.compile(r"[^a-z0-9-]")


def _slugify(text: str) -> str:
    """Lowercase, spaces/slashes/commas/parens → hyphens, strip special chars."""
    t = text.lower()
    t = _SLUG_TO_HYPHEN.sub("-", t)   # convert separators to hyphens first
    t = _SLUG_STRIP.sub("", t)         # strip remaining non-alphanumeric chars
    t = re.sub(r"-+", "-", t).strip("-")
    return t


# ---------------------------------------------------------------------------
# USDM index builder
# ---------------------------------------------------------------------------

def _build_index(data: dict) -> dict:
    """
    Walk the entire USDM JSON tree and build a flat id→object index.
    Any object with an "id" field (non-null) is indexed.
    """
    index: dict = {}

    def _walk(node):
        if isinstance(node, dict):
            nid = node.get("id")
            if nid:
                index[nid] = node
            for v in node.values():
                _walk(v)
        elif isinstance(node, list):
            for item in node:
                _walk(item)

    _walk(data)
    return index


# ---------------------------------------------------------------------------
# Unit extraction from a BiomedicalConcept
# ---------------------------------------------------------------------------

def _extract_unit(bc: dict) -> str:
    """
    Return the unit string for a BiomedicalConcept.

    Strategy (per spec §2.8):
      1. Find the property whose name starts with "VSORRES" (result-value property).
         The *next* property (VSORRESU) carries the unit.
      2. If the VSORRESU property has responseCodes, use the first responseCode's
         code.decode as the unit string.
      3. If no responseCodes, use the VSORRESU property's code.standardCode.decode.
      4. If no VSORRESU property found, return "".

    The USDM uses CDISC decode strings (e.g. "Degree Celsius", "Kilogram").
    We return those as-is; downstream enrichment (F-5b) can map to UCUM.
    """
    props = bc.get("properties", [])
    for i, prop in enumerate(props):
        name = prop.get("name", "")
        # Match VSORRESU-style property (unit property)
        if re.match(r"VSORRESU", name, re.IGNORECASE) or re.match(r".*ORRESU.*", name):
            # Try responseCodes first
            rc = prop.get("responseCodes", [])
            if rc:
                return rc[0].get("code", {}).get("decode", "")
            # Fall back to property code decode
            code_obj = prop.get("code", {})
            sc = code_obj.get("standardCode", {})
            return sc.get("decode", "")
    return ""


def _extract_datatype(bc: dict) -> str:
    """
    Return "Quantity" for numeric BCs, "string" for non-numeric.

    Looks for the VSORRES property (result value) and checks its datatype field.
    Numeric datatypes: float, integer, decimal, number.
    """
    props = bc.get("properties", [])
    for prop in props:
        name = prop.get("name", "")
        if re.match(r"VSORRES", name, re.IGNORECASE) or re.match(r".*ORRES(?!U).*", name):
            dt = prop.get("datatype", "").lower()
            if dt in ("float", "integer", "decimal", "number", "int"):
                return "Quantity"
            if dt:
                return "string"
    return "string"


