def main(argv=None):
    import argparse
    parser = argparse.ArgumentParser(
        description="Extract activity and observation catalogs from a USDM JSON file."
    )
    parser.add_argument("usdm_path", help="Path to USDM JSON file")
    parser.add_argument(
        "--activity-out",
        default="input/data/usdm-activity-catalog.csv",
        help="Output path for activity catalog CSV",
    )
    parser.add_argument(
        "--observation-out",
        default="input/data/usdm-observation-catalog.csv",
        help="Output path for observation catalog CSV",
    )
    parser.add_argument(
        "--soa-matrix-out",
        default="input/data/usdm-soa-matrix.csv",
        help="Output path for SoA matrix CSV",
    )
    args = parser.parse_args(argv)

    logging.basicConfig(level=logging.INFO, format="%(levelname)s: %(message)s")

    act_rows = extract_activity_catalog(args.usdm_path)
    obs_rows = extract_observation_catalog(args.usdm_path)

    write_activity_catalog(act_rows, args.activity_out)
    write_observation_catalog(obs_rows, args.observation_out)

    print(f"Activity catalog:    {len(act_rows)} rows → {args.activity_out}")
    print(f"Observation catalog: {len(obs_rows)} rows → {args.observation_out}")

    # Summary by archetype
    from collections import Counter
    arch_counts = Counter(r["archetype"] for r in act_rows)
    for arch, cnt in sorted(arch_counts.items()):
        print(f"  {arch}: {cnt}")

    # SoA matrix (requires activity catalog to already be written)
    soa_result = extract_soa_matrix(args.usdm_path, args.activity_out)
    write_soa_matrix(soa_result, args.soa_matrix_out)
    n_rows = len(soa_result["rows"])
    n_cols = len(soa_result["encounter_names"])
    print(f"SoA matrix:          {n_rows} activities × {n_cols} encounters → {args.soa_matrix_out}")


if __name__ == "__main__":
    main()
